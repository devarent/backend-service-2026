-- Order management schema.
-- PostgreSQL 16 is the production target. The script is also H2 PostgreSQL-mode
-- friendly, but the test profile intentionally uses Hibernate drop-and-create
-- so unit/integration tests do not require a database container.

CREATE TABLE orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id        UUID           NOT NULL,
    customer_id      VARCHAR(64)    NOT NULL,
    customer_name    VARCHAR(200)   NOT NULL,
    customer_email   VARCHAR(320)   NOT NULL,
    status           VARCHAR(32)    NOT NULL,
    currency         VARCHAR(3)     NOT NULL,
    subtotal         NUMERIC(19, 2) NOT NULL,
    tax_amount       NUMERIC(19, 2) NOT NULL,
    total_amount     NUMERIC(19, 2) NOT NULL,
    idempotency_key  VARCHAR(128),
    version          BIGINT         NOT NULL DEFAULT 0,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_orders_public_id UNIQUE (public_id),
    CONSTRAINT uq_orders_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_orders_status CHECK (
        status IN ('PENDING', 'CONFIRMED', 'PROCESSING', 'SHIPPED', 'DELIVERED', 'CANCELLED')
    ),
    CONSTRAINT ck_orders_amounts CHECK (
        subtotal >= 0 AND tax_amount >= 0 AND total_amount >= 0
        AND total_amount = subtotal + tax_amount
    ),
    CONSTRAINT ck_orders_currency CHECK (char_length(currency) = 3)
);

CREATE TABLE order_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT         NOT NULL,
    product_sku   VARCHAR(64)    NOT NULL,
    product_name  VARCHAR(200)   NOT NULL,
    quantity      INTEGER        NOT NULL,
    unit_price    NUMERIC(19, 2) NOT NULL,
    line_total    NUMERIC(19, 2) NOT NULL,
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_items_unit_price CHECK (unit_price >= 0),
    CONSTRAINT ck_order_items_line_total CHECK (line_total >= 0)
);

CREATE INDEX idx_orders_status_created_at ON orders (status, created_at DESC);
CREATE INDEX idx_orders_created_at ON orders (created_at DESC);
CREATE INDEX idx_orders_customer_id ON orders (customer_id);
CREATE INDEX idx_order_items_order_id ON order_items (order_id);

COMMENT ON TABLE orders IS 'Order aggregate root. Cancellation is a status transition, never a hard delete.';
COMMENT ON COLUMN orders.idempotency_key IS 'Optional client-supplied key that makes order creation safe to retry.';
COMMENT ON COLUMN orders.version IS 'Optimistic locking version managed by Hibernate.';
